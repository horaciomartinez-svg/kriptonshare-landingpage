/* ---------- Engine ---------- */
(function () {
  const SUPPORTED = ['en', 'es'];
  const stored = localStorage.getItem('ks-lang');
  const browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
  let lang = stored || (SUPPORTED.includes(browser) ? browser : 'en');

  function t(key) {
    return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  }

  function apply() {
    document.documentElement.lang = lang;
    document.body.classList.remove('lang-en', 'lang-es');
    document.body.classList.add('lang-' + lang);
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
    const page = document.body.dataset.page || 'home';
    const title = t('meta.' + page + '.title');
    if (title && !title.startsWith('meta.')) document.title = title;
    const md = document.querySelector('meta[name="description"]');
    const desc = t('meta.' + page + '.desc');
    if (md && desc && !desc.startsWith('meta.')) md.setAttribute('content', desc);
    document.querySelectorAll('.lang-toggle button').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });
    document.dispatchEvent(new CustomEvent('ks:lang', { detail: { lang } }));
  }

  window.KS_I18N = {
    t,
    get lang() { return lang; },
    set(l) {
      if (!SUPPORTED.includes(l)) return;
      lang = l;
      localStorage.setItem('ks-lang', l);
      apply();
    }
  };

  document.addEventListener('DOMContentLoaded', apply);
})();
